"""Run the execution simulator studies and write research/results_sim.md.

Run from anywhere:  python research/run_sim.py [--workers 6] [--seeds 20] [--quick]

Everything is seeded, so results do not depend on the worker count.  All flow
parameters are assumed; see the limits section of the output.
"""

from __future__ import annotations

import argparse
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from dataclasses import replace
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python" / "src"))

from lobmod.sim import (  # noqa: E402
    AgentSpec, AvellanedaStoikov, FlowParams, NaiveTouch, SignalTaker, Simulator, assess_edge,
    fill_prob_by_queue, legacy_maker, realised_spread, summarise, variance_ratio,
)

T = 600.0
LATS = (0.0005, 0.002, 0.01, 0.03, 0.1, 0.3)
HORIZONS = (0.1, 1.0, 5.0, 30.0)
BASE_LAT = 0.01
EXTRA_LATS = (0.002, 0.03, 0.1)
STRATS = {"naive": NaiveTouch, "as": AvellanedaStoikov, "taker": SignalTaker}
LEGACY_SEEDS = [s * 7919 for s in range(1, 21)]


def one(job):
    """job = (key, strategy, cap, latency, flow overrides, signal, fast rival, seed)."""
    key, strat, cap, lat, over, signal, fast, seed = job
    agents = [AgentSpec("a", STRATS[strat](cap=cap), lat, lat, sees_signal=signal)]
    if fast:
        agents.append(AgentSpec("fast", NaiveTouch(), 0.0002, 0.0002, size=3))
    res = Simulator(replace(FlowParams(), **over), agents, T, seed).run()
    out = summarise(res, "a")
    out["rs"] = realised_spread(res, "a", HORIZONS)
    out["queue"] = fill_prob_by_queue(res, "a")
    return key, seed, out


def legacy_job(job):
    seed, cap = job
    return seed, cap, legacy_maker(seed, 0, cap)


def ci(x):
    """Mean and approximate 95% t interval across seeds."""
    x = np.asarray(x, float)
    half = (1.96 + 2.4 / (len(x) - 1)) * x.std(ddof=1) / np.sqrt(len(x))
    return float(x.mean()), float(x.mean() - half), float(x.mean() + half)


def fmt(x, d=1):
    m, lo, hi = ci(x)
    return f"{m:.{d}f} [{lo:.{d}f}, {hi:.{d}f}]"


def col(rows, name):
    return np.array([r[name] for r in rows], float)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--quick", action="store_true", help="smoke run; numbers mean little")
    args = ap.parse_args()
    n_seeds = 4 if args.quick else args.seeds
    seeds = [1000 + 17 * i for i in range(n_seeds)]
    t0 = time.time()

    specs = {}
    for s in STRATS:
        for lat in LATS:
            specs[("lat", s, lat)] = (s, 5, lat, {}, True, False)
    for lat in EXTRA_LATS:
        specs[("nosig", lat)] = ("naive", 5, lat, {}, False, False)
        specs[("rival", lat)] = ("naive", 5, lat, {}, True, True)
        specs[("noinf", lat)] = ("naive", 5, lat, {"p_informed": 0.0}, True, False)
    harsh = {"jump_rate": 0.9, "informed_per_jump": 4}
    for name, over in (("off", {"p_informed": 0.0}), ("half", {"p_informed": 0.5}), ("base", {}), ("harsh", harsh)):
        specs[("inf", name)] = ("naive", 5, BASE_LAT, over, True, False)
    for lat in (0.002, 0.1):
        specs[("harshlat", lat)] = ("naive", 5, lat, harsh, True, False)
    caps = (1, 2, 5, 20, 80)
    for cap in caps:
        specs[("cap", cap)] = ("naive", cap, BASE_LAT, {}, True, False)
    jobs = [(k, *v, s) for k, v in specs.items() for s in seeds]
    lcaps = (5, 10, 20, 40)
    ljobs = [(s, c) for s in (LEGACY_SEEDS[:4] if args.quick else LEGACY_SEEDS) for c in lcaps]

    R = {k: {} for k in specs}
    L = {c: {} for c in lcaps}
    with ProcessPoolExecutor(args.workers) as ex:
        lf = ex.map(legacy_job, ljobs, chunksize=4)
        for k, s, o in ex.map(one, jobs, chunksize=8):
            R[k][s] = o
        for s, c, o in lf:
            L[c][s] = o
        vr = list(ex.map(variance_ratio, LEGACY_SEEDS[:4] if args.quick else LEGACY_SEEDS))
    rows = {k: [R[k][s] for s in seeds] for k in specs}
    lseeds = sorted(L[5])

    w = []
    p = w.append
    p("# Execution simulator results\n")
    p(f"Generated by `research/run_sim.py`: {n_seeds} seeds, {T:.0f} s of clock time per run, one lot per quote. "
      "P&L is in ticks per run. Brackets are approximate 95% t intervals across seeds. "
      "Latency is the one-way delay, applied to market data and to order entry alike.\n")
    p("**Limits.** This is uncalibrated synthetic flow and every parameter is assumed. Levels of P&L mean nothing "
      "outside this model. Only signs and orderings inside the model are worth reading, and those depend on the "
      "assumptions listed at the end. Nothing here is evidence of a tradable edge.\n")

    # ---- acceptance
    p("## Acceptance checks\n")
    fast_, slow = rows[("lat", "naive", 0.002)], rows[("lat", "naive", 0.1)]
    d = col(fast_, "total") - col(slow, "total")
    m, lo, hi = ci(d)
    a1 = lo > 0
    p(f"1. **Latency hurts the maker with informed flow on: {'PASS' if a1 else 'FAIL'}.** Naive maker, 2 ms minus "
      f"100 ms, paired by seed: {m:.1f} [{lo:.1f}, {hi:.1f}] ticks. AS maker: "
      f"{fmt(col(rows[('lat', 'as', 0.002)], 'total') - col(rows[('lat', 'as', 0.1)], 'total'))}. "
      f"With informed flow off, the naive difference is "
      f"{fmt(col(rows[('noinf', 0.002)], 'total') - col(rows[('noinf', 0.1)], 'total'))}. "
      f"With no signal feed it is {fmt(col(rows[('nosig', 0.002)], 'total') - col(rows[('nosig', 0.1)], 'total'))}.\n")

    inv_lo, inv_hi = rows[("cap", 2)], rows[("cap", 80)]
    m80, l80, h80 = ci(col(inv_hi, "inventory"))
    sd2, sd80 = col(inv_lo, "total").std(ddof=1), col(inv_hi, "total").std(ddof=1)
    a2 = sd80 > sd2 and l80 <= 0 <= h80
    p(f"2. **Looser cap adds risk, not free money: {'PASS' if a2 else 'FAIL'}.** Between caps 2 and 80, the seed sd of "
      f"P&L goes {sd2:.1f} to {sd80:.1f}, and the inventory term at cap 80 is {m80:.1f} [{l80:.1f}, {h80:.1f}], "
      f"which {'includes' if l80 <= 0 <= h80 else 'excludes'} zero. Any rise in the mean comes from extra spread "
      "capture on more fills, shown in the cap table.\n")

    off = ci(col(rows[("inf", "off")], "total"))
    verdict = assess_edge(*off, 0.0, 0.0)
    p(f"3. **Zero informed flow and zero fees is not presented as an edge: {'PASS' if verdict.startswith('not an edge') else 'FAIL'}.** "
      f"P&L {off[0]:.1f} [{off[1]:.1f}, {off[2]:.1f}]. Verdict: {verdict}. Fair value still jumps here; only the takers who trade on it are gone.\n")

    # ---- latency
    def cell(kind, lat):
        return fmt(col(rows[(kind, lat)], "total")) if (kind, lat) in rows else "not run"

    p("## Latency sensitivity (total P&L)\n")
    p("| one-way ms | naive | AS | taker | naive, no signal | naive vs fast rival | naive, no informed |")
    p("|---|---|---|---|---|---|---|")
    for lat in LATS:
        p(f"| {lat * 1000:g} | {fmt(col(rows[('lat', 'naive', lat)], 'total'))} | {fmt(col(rows[('lat', 'as', lat)], 'total'))} "
          f"| {fmt(col(rows[('lat', 'taker', lat)], 'total'))} | {cell('nosig', lat)} "
          f"| {cell('rival', lat)} | {cell('noinf', lat)} |")
    p("\n| one-way ms | naive lots | naive late cancels | share of naive lots hit by informed | lots vs fast rival |")
    p("|---|---|---|---|---|")
    for lat in LATS:
        r = rows[("lat", "naive", lat)]
        p(f"| {lat * 1000:g} | {col(r, 'lots').mean():.0f} | {col(r, 'late_cancels').mean():.0f} "
          f"| {col(r, 'informed_share').mean():.3f} | "
          + (f"{col(rows[('rival', lat)], 'lots').mean():.0f} |" if ("rival", lat) in rows else "not run |"))

    # ---- informed
    p("\n## Informed intensity (naive, 10 ms, no fees)\n")
    p("| flow | P&L | per lot | verdict |\n|---|---|---|---|")
    for name, label, pi in (("off", "none", 0.0), ("half", "half", 0.5), ("base", "base", 1.0), ("harsh", "3x jumps, 4 takers per jump", 1.0)):
        r = rows[("inf", name)]
        c = ci(col(r, "total"))
        p(f"| {label} | {fmt(col(r, 'total'))} | {fmt(col(r, 'total') / col(r, 'lots'), 3)} | {assess_edge(*c, pi, 0.0)} |")
    p(f"\nUnder the harsh flow, 2 ms minus 100 ms is {fmt(col(rows[('harshlat', 0.002)], 'total') - col(rows[('harshlat', 0.1)], 'total'))}.")

    # ---- fees
    p("\n## Fee breakeven\n")
    p("Fee per lot at which mean P&L is zero, equal to gross P&L per lot. A maker fee above this loses. "
      "Maker quotes ignore fees, so fills do not change with the fee and this is exact for the makers. "
      "The taker's threshold moves with its fee, so its figure is computed at zero fee and is approximate.\n")
    p("| one-way ms | naive | AS | taker |\n|---|---|---|---|")
    for lat in LATS:
        cells = []
        for s in STRATS:
            r = rows[("lat", s, lat)]
            cells.append(f"{col(r, 'total').sum() / max(col(r, 'lots').sum(), 1):.3f}")
        p(f"| {lat * 1000:g} | " + " | ".join(cells) + " |")

    # ---- attribution
    p(f"\n## Attribution at {BASE_LAT * 1000:g} ms (adverse window 1 s, zero fees)\n")
    p("| strategy | spread | adverse | inventory | total | lots |\n|---|---|---|---|---|---|")
    for s in STRATS:
        r = rows[("lat", s, BASE_LAT)]
        p(f"| {s} | {fmt(col(r, 'spread'))} | {fmt(col(r, 'adverse'))} | {fmt(col(r, 'inventory'))} | {fmt(col(r, 'total'))} | {col(r, 'lots').mean():.0f} |")
    p("\nThe fee line is zero here by choice; the breakeven table prices fees. The makers and taker hold a free "
      "delayed fair-value feed, so a positive adverse term means they tended to trade the right way.\n")
    p("Realised spread per lot by horizon:\n")
    p("| strategy | " + " | ".join(f"{h:g} s" for h in HORIZONS) + " |\n|---|" + "---|" * len(HORIZONS))
    for s in STRATS:
        r = rows[("lat", s, BASE_LAT)]
        p(f"| {s} | " + " | ".join(fmt([o["rs"][h] for o in r if np.isfinite(o["rs"][h])], 3) for h in HORIZONS) + " |")

    p("\nFill probability by lots ahead at entry, seeds pooled. Pulled orders count as unfilled, "
      "and the naive quoter requotes often, so these are low by design of the strategy:\n")
    p("| lots ahead | naive orders | naive filled | AS orders | AS filled |\n|---|---|---|---|---|")
    pooled = {}
    for s in ("naive", "as"):
        for o in rows[("lat", s, BASE_LAT)]:
            for b, (n, f) in o["queue"].items():
                a = pooled.setdefault((s, b), [0, 0])
                a[0] += n
                a[1] += f
    for b in rows[("lat", "naive", BASE_LAT)][0]["queue"]:
        cells = []
        for s in ("naive", "as"):
            n, f = pooled[(s, b)]
            cells += [str(n), f"{f / n:.3f}" if n else "n/a"]
        p(f"| {b} | " + " | ".join(cells) + " |")

    # ---- caps
    p("\n## Inventory cap (naive, 10 ms)\n")
    p("| cap | total | seed sd | spread | adverse | inventory | lots | max abs inventory |\n|---|---|---|---|---|---|---|---|")
    for cap in caps:
        r = rows[("cap", cap)]
        p(f"| {cap} | {fmt(col(r, 'total'))} | {col(r, 'total').std(ddof=1):.1f} | {fmt(col(r, 'spread'))} | {fmt(col(r, 'adverse'))} "
          f"| {fmt(col(r, 'inventory'))} | {col(r, 'lots').mean():.0f} | {col(r, 'max_inv').mean():.1f} |")

    # ---- legacy
    p("\n## Why the old simulator showed +362 at cap 20\n")
    p("Replica of the review's maker on the same 20 seeds, delay 0. `spread` is capture against the pre-fill mid and "
      "`position` is inventory times mid change; they sum to P&L exactly.\n")
    p("| cap | P&L | seed sd | spread | position | fills | mean abs inventory |\n|---|---|---|---|---|---|---|")
    for c in lcaps:
        r = [L[c][s] for s in lseeds]
        p(f"| {c} | {fmt(col(r, 'pnl'))} | {col(r, 'pnl').std(ddof=1):.1f} | {fmt(col(r, 'spread'))} | {fmt(col(r, 'position'))} "
          f"| {col(r, 'fills').mean():.0f} | {col(r, 'mean_abs_inv').mean():.1f} |")
    r5, r20 = [L[5][s] for s in lseeds], [L[20][s] for s in lseeds]
    dp = col(r20, "pnl") - col(r5, "pnl")
    dpos = col(r20, "position") - col(r5, "position")
    dsp = col(r20, "spread") - col(r5, "spread")
    share = dpos.mean() / dp.mean()
    p(f"\nCap 20 minus cap 5, paired: P&L {fmt(dp)}, of which position {fmt(dpos)} ({share:.0%}) and spread {fmt(dsp)}.\n")
    hs = sorted(vr[0])
    p("Variance ratio of the zero-intelligence mid (1 is a random walk), mean over seeds: "
      + ", ".join(f"{h} events {np.mean([v[h] for v in vr]):.2f}" for h in hs) + ".\n")
    p("Reading: the zero-intelligence stream places limit orders relative to the opposite best, with no fair value, so "
      "its mid mean-reverts at long horizons, as the falling variance ratio shows. A maker is contrarian: it buys falls and "
      "sells rises. The position term is the cost of holding that inventory, and a wider cap shrinks the loss because a "
      "bigger contrarian book is paid by the reversion instead of being forced out at the cap. That looks like a property of the "
      "generator, not of the strategy. On the martingale fair value above, the same looser cap shows no such gain in the "
      "inventory term. This evidence is an attribution and a variance ratio, not a controlled removal of the reversion "
      "from the old stream; the later controls in results_control.md are inconclusive, so reversion is only partly supported as the cause. The old replay also never reacts to the injected orders, which is not separately measured here.\n")

    # ---- assumptions
    fp = FlowParams()
    p("## Assumptions that drive these results\n")
    p(f"- Fair value: compound Poisson, {fp.jump_rate}/s, sd {fp.jump_sd} ticks. Informed: {fp.informed_per_jump} slots per jump, "
      f"mean delay {fp.informed_delay * 1000:g} ms, up to {fp.informed_size} lots.")
    p("- Agents get a free fair-value feed, delayed by their market-data latency. This creates the cancel race. "
      "The no-signal column shows what is left without it.")
    p("- The background book follows fair value with a "
      f"{fp.anchor_tau * 1000:g} ms lag and is not competitive: nothing drives maker profit to zero except the optional fast rival, "
      "so positive maker P&L at base flow reflects the assumed share of uninformed flow.")
    p(f"- Hawkes market flow mu {tuple(fp.mu)}, beta {fp.beta}, sizes 1 to 3; it does not react to the book or to the agents.")
    p("- Latency is fixed with no jitter. No exchange throttles, no partial-size logic beyond the book, marks at final mid, no funding or capital cost.")
    p("- Parameters were set once by judgement and were not fitted to data. Harsh flow and no-signal runs are there to show how far the conclusions move.")
    p(f"\nRuntime {time.time() - t0:.0f} s with {args.workers} workers.")
    (ROOT / "research" / "results_sim.md").write_text("\n".join(w) + "\n", encoding="utf-8")
    print(f"done in {time.time() - t0:.0f} s; acceptance latency={a1} cap={a2}")


if __name__ == "__main__":
    main()
